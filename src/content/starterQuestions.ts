// Each answer was read in the source named beside it (rule 7). Sums use a fact from the source.
const ecfr = (part: string, title: string): Source => ({ title, url: `https://www.ecfr.gov/current/title-21/chapter-II/part-${part}` });
const label = (title: string, setid: string): Source => ({
  title: `${title} label, DailyMed`,
  url: `https://dailymed.nlm.nih.gov/dailymed/drugInfo.cfm?setid=${setid}`,
});

// The label a drug card was checked against; `slug` is the card's id without "drug-".
function card(slug: string): Source {
  const drug = drugCards.find((c) => c.id === `drug-${slug}`);
  if (drug === undefined) throw new Error(`No drug card drug-${slug}`);
  return drug.source;
}

// The same label titled by its generic, so a brand-name question isn't answered by another's source.
function byGeneric(slug: string): Source {
  return { ...card(slug), title: `${slug.charAt(0).toUpperCase()}${slug.slice(1)} label, DailyMed` };
}

